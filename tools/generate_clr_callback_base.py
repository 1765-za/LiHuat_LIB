#!/usr/bin/env python3
"""Generate callback no-ops from the pinned, official .NET 10 corprof.h.

No network access, ABI declarations, or dependencies outside the Python stdlib.
See docs/profiler-build-inputs.md for input acquisition and compilation checks.
"""
import argparse
import hashlib
from pathlib import Path
import re
import sys

COMMIT = "60629d14374c56f1cb51819049ad1fa529307f8d"
SHA256 = "6892e8f1c8492290d19cd9c9b3f73d840f02b05cdcee8ba344ab3614ad66406a"
COUNTS = (69, 8, 3, 6, 1, 1, 1, 2, 1, 2, 1)
OUTPUTS = {
    "JITCachedFunctionSearchStarted": ("pbUseCachedFunction", "TRUE"),
    "JITInlining": ("pfShouldInline", "TRUE"),
    "LoadAsNotificationOnly": ("pbNotificationOnly", "FALSE"),
}


def generate(data):
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError("Input is not the pinned dotnet/runtime v10.0.0 corprof.h")
    source = data.decode("utf-8")
    lines = [
        "// Generated by tools/generate_clr_callback_base.py; do not edit.",
        "// Signatures: dotnet/runtime v10.0.0, commit " + COMMIT,
        "// Source SHA-256: " + SHA256,
        "// .NET Foundation interface signatures are MIT licensed; see docs/profiler-build-inputs.md.",
        "#pragma once", "",
        "// Include the platform's verified CLR interfaces before this file.",
        "// IUnknown ownership and identity remain abstract and must be supplied by the profiler.",
        "class ClrCallbackBase : public ICorProfilerCallback11 {", "public:",
    ]
    seen = set()
    parent = "IUnknown"
    for version, count in enumerate(COUNTS, 1):
        interface = "ICorProfilerCallback" + (str(version) if version > 1 else "")
        block = re.search(r"\b" + interface + r" : public (\w+)\s*\{\s*public:(.*?)\n    };", source, re.S)
        if not block or block[1] != parent:
            raise ValueError("Unexpected inheritance: " + interface)
        methods = re.findall(r"virtual HRESULT STDMETHODCALLTYPE (\w+)\(\s*(.*?)\) = 0;", block[2], re.S)
        if len(methods) != count or block[2].count("virtual ") != count:
            raise ValueError("Unexpected method count: " + interface)
        lines.append("    // " + interface)
        for name, raw_parameters in methods:
            if name in seen:
                raise ValueError("Duplicate callback: " + name)
            seen.add(name)
            output = OUTPUTS.get(name)
            parameters = []
            for parameter in re.sub(r"/\*.*?\*/", "", raw_parameters, flags=re.S).split(","):
                parameter = " ".join(parameter.split())
                if parameter == "void":
                    continue
                match = re.fullmatch(r"(.+?)(\w+)(\[\s*\])?", parameter)
                if not match:
                    raise ValueError("Unsupported parameter: " + parameter)
                # Omit unused names, retaining pointer and array type syntax verbatim.
                parameters.append(match[1].rstrip() + (" " + match[2] if output and match[2] == output[0] else "") + (match[3] or ""))
            body = "return S_OK;"
            if output:
                pointer, value = output
                body = f"if (!{pointer}) return E_POINTER; *{pointer} = {value}; return S_OK;"
            if name in ("Initialize", "InitializeForAttach"):
                body = "return E_NOTIMPL;"  # Concrete profiler must initialize its state.
            lines.append(f"    HRESULT STDMETHODCALLTYPE {name}({', '.join(parameters)}) override {{ {body} }}")
        parent = interface
    lines += ["};", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("corprof", type=Path)
    parser.add_argument("--output", type=Path, default=Path(__file__).resolve().parents[1] / "Source.Native/Waylith/ClrCallbackBase.h")
    parser.add_argument("--check", action="store_true", help="Fail if output is missing or differs; do not modify it")
    args = parser.parse_args()
    try:
        result = generate(args.corprof.read_bytes())
        if args.check:
            if args.output.read_bytes() != result.encode("utf-8"):
                raise ValueError("Generated callback header is stale")
        else:
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_bytes(result.encode("utf-8"))
    except (OSError, ValueError) as error:
        print(error, file=sys.stderr)
        return 1
    print(f"Verified {sum(COUNTS)} callback methods: {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
